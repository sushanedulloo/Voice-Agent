def apply(translations, scopes):
    faq_dir = ROOT / "content" / "faq"
    stats, problems = {"q": 0, "a": 0, "missing": 0}, []
    for scope in scopes:
        path = faq_dir / f"{scope}.yaml"
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        for entry in doc["entries"]:
            per_locale = translations.get(entry["id"])
            if not per_locale:
                stats["missing"] += 1
                continue
            english = entry["answer"]["en"]
            for locale, pair in per_locale.items():
                entry["question"][locale] = pair[Q]
                stats["q"] += 1
                if set(SLOT.findall(english)) != set(SLOT.findall(pair[A])):
                    problems.append(f"{entry['id']}/{locale}: slot mismatch")
                    continue
                entry["answer"][locale] = pair[A]
                stats["a"] += 1
        head = path.read_text(encoding="utf-8").split("scope:")[0]
        path.write_text(head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True,
                                              width=200), encoding="utf-8")
    for p in problems:
        print("  SLOT MISMATCH " + p)
    print(f"  {stats['q']} questions, {stats['a']} answers translated; "
          f"{stats['missing']} entries not in this batch")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(apply(T, ["common"]))
