def main():
    path = ROOT / "content" / "intents.yaml"
    doc = yaml.safe_load(path.read_text(encoding="utf-8"))
    added = 0
    for locale, intents in EXAMPLES.items():
        for name, examples in intents.items():
            if name not in doc["intents"]:
                print(f"  ! unknown intent {name!r}, skipped")
                continue
            doc["intents"][name][f"examples_{locale}"] = examples
            added += len(examples)

    header = path.read_text(encoding="utf-8").split("intents:")[0]
    buf = io.StringIO()
    buf.write(header)
    buf.write(yaml.safe_dump({"intents": doc["intents"]}, sort_keys=False,
                             allow_unicode=True, width=120))
    path.write_text(buf.getvalue(), encoding="utf-8")
    print(f"  {added} examples across {len(EXAMPLES)} languages -> {path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
